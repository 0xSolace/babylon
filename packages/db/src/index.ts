/**
 * Drizzle ORM Database Layer — public API
 *
 * **What belongs here:** table-related **types**, **named query functions** (see
 * `*-queries.ts`), shared helpers (snowflake, moderation), and a few client **types**.
 *
 * **What does not:** Drizzle SQL builders (`eq`, `and`, `sql`, …). Import those from
 * `drizzle-orm` so this package is not a second copy of Drizzle’s surface area.
 *
 * **Runtime:** `db`, table **values**, `asUser` / `asSystem` / `asPublic` → `@babylon/db/engine-storage` (RLS/session boundaries — not re-exported here so the split stays obvious). **`withTransaction`** is exported from this barrel for orchestration that already uses named queries from `@babylon/db`.
 *
 * **Why split:** Keeps query review centralized, avoids circular imports with this
 * barrel, and documents RLS expectations. See `docs/database-layer.md`.
 */

